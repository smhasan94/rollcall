#!/usr/bin/env python3
"""Derives the fork revision -> upstream version tables of the identifier database.

Run through scripts/regen-version-tables.sh, which fetches the Zephyr manifests first. Python 3
standard library only.

    version-tables.py --manifests DIR --db FILE --pins FILE --cache DIR
    version-tables.py --self-test          # offline checks of the parsers; no network

For every Zephyr release whose `west.yml` is in DIR, every pinned revision of every module in
DERIVE gets an upstream version, by one of:

  file    read a version file of the fork at that revision (raw.githubusercontent.com) and
          match a regex; the version is built from the named groups with `fmt`.
  tag     the newest upstream release tag (matching `tag`) that is an ancestor of the fork
          revision, found in a blobless clone (`git fetch --filter=tree:0`) of fork + upstream.
  self    the module is its own upstream (a Zephyr-maintained aggregate of vendor code); the
          version is the commit itself.
  log     the version in the newest commit subject of the fork (matching `regex`), for forks
          that import upstream releases as snapshots and name the release when they do.
  manual  nothing is derived; every pinned revision must already have a hand-curated row
          (outside the generated markers) in FILE, citing its source.

The rows are written between the `# BEGIN generated` and `# END generated` markers inside
each module's `table:` in FILE; nothing else in FILE is touched. Revisions and versions are
single-quoted so a hex revision such as `1e75...` is never read as a number.

The pin list (every module, revision and the releases pinning it) is written to --pins; the
coverage tests read it offline.

Exits 1 if any pinned revision of a seeded module has no version (no silent gaps).
"""

